CREATE DATABASE SPARTANFIT
COLLATE Latin1_General_100_CI_AS_SC_UTF8;
GO

USE SPARTANFIT;
GO

CREATE TABLE USUARIO (
ID_USUARIO INT IDENTITY (1,1) PRIMARY KEY,
USUARIO NVARCHAR (100) NOT NULL UNIQUE,
PASSWORD_HASH VARCHAR (200) NOT NULL,
ESTADO VARCHAR (50) NOT NULL DEFAULT 'ACTIVO',
FECHA_CREACION DATETIME2 (0) NOT NULL DEFAULT SYSUTCDATETIME()
);
GO

CREATE TABLE MIEMBRO (
    ID_MIEMBRO INT IDENTITY(1,1) PRIMARY KEY,
    ID_USUARIO INT NOT NULL,
    CI VARCHAR(15) NOT NULL UNIQUE,
    NOMBRE NVARCHAR(50) NOT NULL,
    APELLIDOS NVARCHAR(50) NOT NULL,
    DIRECCION NVARCHAR(150),
    TELEFONO VARCHAR(12),
    CORREO_ELECTRONICO NVARCHAR(100),
    FECHA_NACIMIENTO DATE NOT NULL,
    CONSTRAINT FK_MIEMBRO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO)
);
GO
CREATE TABLE  COACH (
    ID_COACH INT IDENTITY(1,1) PRIMARY KEY,
    ID_USUARIO INT NOT NULL,
    CI VARCHAR (20) NOT NULL UNIQUE,                               
    CODIGO VARCHAR(20) NOT NULL UNIQUE,
    NOMBRE NVARCHAR(50) NOT NULL,                  
    APELLIDO NVARCHAR(50) NOT NULL,                
    DIRECCION NVARCHAR(200),                       
    TELEFONO VARCHAR(20),                          
    CONSTRAINT FK_COACH_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO)
);
GO

CREATE TABLE ESPECIALIDAD (
    ID_ESPECIALIDAD INT IDENTITY(1,1) PRIMARY KEY,
    NOMBRE NVARCHAR(50) NOT NULL UNIQUE
);
GO

CREATE TABLE COACH_ESPECIALIDAD (
    ID_COACH INT NOT NULL,
    ID_ESPECIALIDAD INT NOT NULL,
    FECHA_EMISION DATE,
    FECHA_EXPIRACION DATE,
    PRIMARY KEY (ID_COACH, ID_ESPECIALIDAD),
    CONSTRAINT FK_COACH_ESPECIALIDAD_COACH FOREIGN KEY (ID_COACH) REFERENCES COACH(ID_COACH),
    CONSTRAINT FK_COACH_ESPECIALIDAD_ESP FOREIGN KEY (ID_ESPECIALIDAD) REFERENCES ESPECIALIDAD(ID_ESPECIALIDAD)
);
GO

--EJERCICIOS
CREATE TABLE EJERCICIOS (
    ID_EJERCICIO INT IDENTITY(1,1) PRIMARY KEY,
    NOMBRE NVARCHAR(100) NOT NULL UNIQUE,
    DESCRIPCION NVARCHAR(255)
);
GO

CREATE TABLE ESTACION (
    ID_ESTACION INT IDENTITY(1,1) PRIMARY KEY,
    NOMBRE NVARCHAR(100) NOT NULL,
    DESCRIPCION NVARCHAR(255),
    EQUIPAMIENTO NVARCHAR(255)
);
GO

CREATE TABLE ESTACION_EJERCICIO (
    ID_ESTACION INT NOT NULL,
    ID_EJERCICIO INT NOT NULL,
    ORDEN INT NOT NULL CHECK (ORDEN > 0),
    NUMERO_SERIES INT CHECK (NUMERO_SERIES > 0),
    REPETICIONES INT CHECK (REPETICIONES > 0),
    TIEMPO VARCHAR(20),
    PRIMARY KEY (ID_ESTACION, ID_EJERCICIO),
    CONSTRAINT FK_ESTACION_EJ_ESTACION FOREIGN KEY (ID_ESTACION) REFERENCES ESTACION(ID_ESTACION),
    CONSTRAINT FK_ESTACION_EJ_EJERCICIO FOREIGN KEY (ID_EJERCICIO) REFERENCES EJERCICIOS(ID_EJERCICIO)
);
GO

CREATE TABLE RUTINAS (
    ID_RUTINA INT IDENTITY(1,1) PRIMARY KEY,
    ID_COACH INT NOT NULL,
    NOMBRE NVARCHAR(100) NOT NULL,
    TIEMPO INT,
    UNIDAD_TIEMPO NVARCHAR(20) DEFAULT N'MINUTOS',
    DESCRIPCION NVARCHAR(255),
    CONSTRAINT FK_RUTINAS_COACH FOREIGN KEY (ID_COACH) REFERENCES COACH(ID_COACH)
);
GO

CREATE TABLE RUTINA_EJERCICIOS (
    ID_RUTINA INT NOT NULL,
    ID_EJERCICIO INT NOT NULL,
    NUMERO_SERIES INT,
    ORDEN INT NOT NULL,
    REPETICIONES INT,
    PRIMARY KEY (ID_RUTINA, ID_EJERCICIO),
    CONSTRAINT FK_RUTINA_EJ_RUTINA FOREIGN KEY (ID_RUTINA) REFERENCES RUTINAS(ID_RUTINA),
    CONSTRAINT FK_RUTINA_EJ_EJERCICIO FOREIGN KEY (ID_EJERCICIO) REFERENCES EJERCICIOS(ID_EJERCICIO)
);
GO

-- INCRIPCION/REGISTRO
CREATE TABLE INSCRIPCION (
    ID_INSCRIPCION INT IDENTITY(1,1) PRIMARY KEY,
    ID_MIEMBRO INT NOT NULL,
    FECHA_INICIO DATE NOT NULL,
    FECHA_FIN DATE NOT NULL,
    MODALIDAD NVARCHAR(50) NOT NULL CONSTRAINT CHK_INSCRIPCION_MODALIDAD CHECK (MODALIDAD IN (N'DIARIO', N'PASADO-DIA', N'MENSUAL')), 
    ESTADO NVARCHAR(20) NOT NULL DEFAULT N'ACTIVO',
    CONSTRAINT FK_INSCRIPCION_MIEMBRO FOREIGN KEY (ID_MIEMBRO) REFERENCES MIEMBRO(ID_MIEMBRO)
);
GO

CREATE TABLE CREDENCIAL (
    ID_CREDENCIAL INT IDENTITY(1,1) PRIMARY KEY,
    ID_MIEMBRO INT NOT NULL,
    TIPO NVARCHAR(50) NOT NULL,
    VALOR VARCHAR(255) NOT NULL UNIQUE,
    ESTADO NVARCHAR(20) NOT NULL DEFAULT N'ACTIVO',
    CONSTRAINT FK_CREDENCIAL_MIEMBRO FOREIGN KEY (ID_MIEMBRO) REFERENCES MIEMBRO(ID_MIEMBRO)
);
GO

CREATE TABLE ASISTENCIAS (
    ID_ASISTENCIA INT IDENTITY(1,1) PRIMARY KEY,
    ID_INSCRIPCION INT NOT NULL,
    ID_CREDENCIAL INT NOT NULL,
    FECHA DATE NOT NULL DEFAULT CAST(SYSUTCDATETIME() AS DATE),
    HORA_ENTRADA TIME(0) NOT NULL DEFAULT CAST(SYSUTCDATETIME() AS TIME),
    CONSTRAINT FK_ASISTENCIAS_INSCRIPCION FOREIGN KEY (ID_INSCRIPCION) REFERENCES INSCRIPCION(ID_INSCRIPCION),
    CONSTRAINT FK_ASISTENCIAS_CREDENCIAL FOREIGN KEY (ID_CREDENCIAL) REFERENCES CREDENCIAL(ID_CREDENCIAL)
);
GO

CREATE TABLE REGISTRO_ESTACION (
    ID_REGISTRO INT IDENTITY(1,1) PRIMARY KEY,
    ID_ESTACION INT NOT NULL,
    ID_MIEMBRO INT NOT NULL,
    FECHA DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME(),
    RESULTADO NVARCHAR(255),
    CONSTRAINT FK_REG_ESTACION_ESTACION FOREIGN KEY (ID_ESTACION) REFERENCES ESTACION(ID_ESTACION),
    CONSTRAINT FK_REG_ESTACION_MIEMBRO FOREIGN KEY (ID_MIEMBRO) REFERENCES MIEMBRO(ID_MIEMBRO)
);
GO

CREATE TABLE REGISTRO_RUTINA (
    ID_REGISTRO INT IDENTITY(1,1) PRIMARY KEY,
    ID_RUTINA INT NOT NULL,
    ID_MIEMBRO INT NOT NULL,
    FECHA DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME(),
    RESULTADO NVARCHAR(255),
    CONSTRAINT FK_REG_RUTINA_RUTINA FOREIGN KEY (ID_RUTINA) REFERENCES RUTINAS(ID_RUTINA),
    CONSTRAINT FK_REG_RUTINA_MIEMBRO FOREIGN KEY (ID_MIEMBRO) REFERENCES MIEMBRO(ID_MIEMBRO)
);
GO

--OBJETIVO
CREATE TABLE OBJETIVO (
    ID_OBJETIVO INT IDENTITY(1,1) PRIMARY KEY,
    ID_MIEMBRO INT NOT NULL,
    TIPO NVARCHAR(50) NOT NULL,
    DESCRIPCION NVARCHAR(255),
    VALOR_INICIAL DECIMAL(6,2) CHECK (VALOR_INICIAL > 0),
    VALOR_META DECIMAL(6,2) CHECK (VALOR_META > 0),
    UNIDAD NVARCHAR(20) DEFAULT N'KG',
    FECHA_INICIO DATE NOT NULL,
    FECHA_FIN DATE,
    CONSTRAINT CK_OBJETIVO_FECHAS CHECK (FECHA_FIN IS NULL OR FECHA_FIN >= FECHA_INICIO),
    CONSTRAINT FK_OBJETIVO_MIEMBRO FOREIGN KEY (ID_MIEMBRO) REFERENCES MIEMBRO(ID_MIEMBRO)
);
GO

CREATE TABLE SEGUIMIENTO (
    ID_SEGUIMIENTO INT IDENTITY(1,1) PRIMARY KEY,
    ID_OBJETIVO INT NOT NULL,
    ID_COACH INT NULL,
    FECHA DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME(),
    VALOR DECIMAL(6,2) NOT NULL,
    COMENTARIO NVARCHAR(255),
    CONSTRAINT FK_SEGUIMIENTO_OBJETIVO FOREIGN KEY (ID_OBJETIVO) REFERENCES OBJETIVO(ID_OBJETIVO),
    CONSTRAINT FK_SEGUIMIENTO_COACH FOREIGN KEY (ID_COACH) REFERENCES COACH(ID_COACH)
);
GO

CREATE TABLE DIETA (
    ID_DIETA INT IDENTITY(1,1) PRIMARY KEY,
    ID_MIEMBRO INT NOT NULL,
    ID_COACH INT NULL,
    FECHA_INICIO DATE NOT NULL,
    FECHA_FIN DATE,
    DESCRIPCION NVARCHAR(255),
    CARBOHIDRATOS_DIARIOS INT CHECK (CARBOHIDRATOS_DIARIOS >= 0),
    CALORIAS_DIARIAS INT CHECK (CALORIAS_DIARIAS >= 0),
    PROTEINAS_DIARIAS INT CHECK (PROTEINAS_DIARIAS >= 0),
    GRASAS_TOTALES INT CHECK (GRASAS_TOTALES >= 0),
    CONSTRAINT CK_DIETA_FECHAS CHECK (FECHA_FIN IS NULL OR FECHA_FIN >= FECHA_INICIO),
    CONSTRAINT FK_DIETA_MIEMBRO FOREIGN KEY (ID_MIEMBRO) REFERENCES MIEMBRO(ID_MIEMBRO),
    CONSTRAINT FK_DIETA_COACH FOREIGN KEY (ID_COACH) REFERENCES COACH(ID_COACH)
);
GO

CREATE TABLE DIETA_DETALLE (
    ID_DETALLE INT IDENTITY(1,1) PRIMARY KEY,
    ID_DIETA INT NOT NULL,
    TIEMPO_COMIDA NVARCHAR(50) NOT NULL,
    DESCRIPCION NVARCHAR(500) NOT NULL,
    CONSTRAINT FK_DIETA_DETALLE_DIETA FOREIGN KEY (ID_DIETA) REFERENCES DIETA(ID_DIETA)
);
GO

