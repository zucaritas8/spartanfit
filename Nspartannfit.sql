GO

CREATE PROCEDURE sp_USUARIO_Login
    @USUARIO NVARCHAR(100),
    @PASSWORD_HASH VARCHAR(200)
AS
BEGIN
    SET NOCOUNT ON;
    SELECT
        U.ID_USUARIO,
        U.USUARIO,
        U.ROL,
        C.ID_COACH,
        M.ID_MIEMBRO,
        CASE
            WHEN U.ROL = 'COACH' THEN ISNULL(C.NOMBRE + N' ' + C.APELLIDO, U.USUARIO)
            WHEN U.ROL = 'MIEMBRO' THEN ISNULL(M.NOMBRE + N' ' + M.APELLIDO, U.USUARIO)
            ELSE N'Administrador General'
        END AS NOMBRE_COMPLETO,
        U.ESTADO
    FROM USUARIO U
    LEFT JOIN COACH C ON C.ID_USUARIO = U.ID_USUARIO
    LEFT JOIN MIEMBRO M ON M.ID_USUARIO = U.ID_USUARIO
    WHERE U.USUARIO = @USUARIO
      AND U.PASSWORD_HASH = @PASSWORD_HASH
      AND U.ROL IN ('ADMIN', 'COACH', 'MIEMBRO');
END;
GO

