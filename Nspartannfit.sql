CREATE PROCEDURE sp_USUARIO_Insertar
    @USUARIO NVARCHAR(100),
    @PASSWORD_HASH VARCHAR(200),
    @ESTADO VARCHAR(50) = 'ACTIVO',
    @ROL VARCHAR(20) = 'MIEMBRO'
AS
BEGIN
    SET NOCOUNT ON;
    INSERT INTO USUARIO (USUARIO, PASSWORD_HASH, ESTADO, FECHA_CREACION, ROL)
    VALUES (@USUARIO, @PASSWORD_HASH, @ESTADO, SYSDATETIME(), @ROL);
END;
GO

CREATE PROCEDURE sp_USUARIO_Editar
    @ID_USUARIO INT,
    @USUARIO NVARCHAR(100),
    @PASSWORD_HASH VARCHAR(200),
    @ESTADO VARCHAR(50),
    @ROL VARCHAR(20)
AS
BEGIN
    SET NOCOUNT ON;
    UPDATE USUARIO
    SET USUARIO = @USUARIO,
        PASSWORD_HASH = @PASSWORD_HASH,
        ESTADO = @ESTADO,
        ROL = @ROL
    WHERE ID_USUARIO = @ID_USUARIO;
END;
GO

CREATE PROCEDURE sp_USUARIO_Eliminar
    @ID_USUARIO INT
AS
BEGIN
    SET NOCOUNT ON;
    UPDATE USUARIO
    SET ESTADO = 'INACTIVO'
    WHERE ID_USUARIO = @ID_USUARIO;
END;
GO

CREATE PROCEDURE sp_USUARIO_Listar
AS
BEGIN
    SET NOCOUNT ON;
    SELECT ID_USUARIO, USUARIO, PASSWORD_HASH, ESTADO, FECHA_CREACION, ROL
